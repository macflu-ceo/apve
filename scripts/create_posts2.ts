async function main() {
  // 테스트 글 삭제
  const del = await prisma.post.deleteMany({ where: { title: "테스트" } });
  if (del.count) console.log(`삭제: 테스트 글 ${del.count}개`);

  for (const p of POSTS) {
    const existing = await prisma.post.findFirst({ where: { title: p.title } });
    const data = { category: p.category, content: p.content, pinned: p.pinned ?? false, published: p.published };
    if (existing) {
      await prisma.post.update({ where: { id: existing.id }, data });
      console.log(`갱신 ${p.published ? "[공개]" : "[비공개]"} ${p.title}`);
    } else {
      await prisma.post.create({ data: { title: p.title, ...data } });
      console.log(`생성 ${p.published ? "[공개]" : "[비공개]"} ${p.title}`);
    }
  }
  console.log("\n✅ 완료.");
}

main().catch((e) => { console.error("오류:", e instanceof Error ? e.message : e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
