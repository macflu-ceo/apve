async function main() {
  const del = await prisma.post.deleteMany({ where: { title: { in: OLD_TITLES } } });
  console.log(`기존 짧은 글 삭제: ${del.count}개`);

  let created = 0, updated = 0;
  for (const p of POSTS) {
    const existing = await prisma.post.findFirst({ where: { title: p.title } });
    if (existing) {
      await prisma.post.update({ where: { id: existing.id }, data: { category: p.category, content: p.content, pinned: p.pinned ?? false, published: p.published } });
      updated++;
    } else {
      await prisma.post.create({ data: { category: p.category, title: p.title, content: p.content, pinned: p.pinned ?? false, published: p.published, imagesJson: "[]" } });
      created++;
    }
    console.log(`  ${existing ? "갱신" : "생성"} [${p.category}]${p.pinned ? "📌" : "  "} ${p.title}`);
  }
  console.log(`\n생성 ${created} · 갱신 ${updated} · 전부 공개`);
}

main().catch((e) => { console.error("오류:", e.message || e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
